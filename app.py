def get_display_prediction(attendance, marks):
    # Normalize inputs
    attendance_score = float(attendance) / 100.0
    marks_score = float(marks) / 100.0
    
    # Weighted formula
    base_score = (0.5 * attendance_score) + (0.5 * marks_score)
    
    # Add small noise
    import random
    noise = random.uniform(-0.02, 0.02)
    final_score = np.clip(base_score + noise, 0.15, 0.92)
    
    return round(float(final_score) * 100, 1)

