"""
SHAP Explainability Engine Module for EduPredict AI.
Computes local and global Shapley feature attribution values and
renders explainable beeswarms, waterfalls, and decision paths.
Includes Streamlit performance caching to prevent redundant calculations.
"""

import streamlit as st
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import shap
import threading
from . import config

# Thread-safe lock for concurrent Matplotlib plot renderings in Streamlit
plot_lock = threading.Lock()

def get_clean_model(model):
    # If the model is a CalibratedClassifierCV, get its first fitted underlying estimator
    if hasattr(model, "calibrated_classifiers_") and len(model.calibrated_classifiers_) > 0:
        return model.calibrated_classifiers_[0].estimator
    return model

def get_explainer(model_bundle):
    """
    Returns the correct SHAP explainer instance based on the active model type.
    """
    model = model_bundle["model"]
    model_type = model_bundle["model_type"]
    
    clean_model = get_clean_model(model)
    try:
        if model_type in ["Random Forest", "XGBoost"]:
            # Use TreeExplainer for tree-based architectures
            return shap.TreeExplainer(clean_model)
        elif model_type == "Logistic Regression":
            # Use LinearExplainer with background training data for linear architectures
            X_train = model_bundle["X_train_df"]
            return shap.LinearExplainer(clean_model, X_train)
        else:
            # Fallback to TreeExplainer on Random Forest
            clean_rf = get_clean_model(model_bundle["rf_model"])
            return shap.TreeExplainer(clean_rf)
    except Exception:
        # Ultimate fallback
        clean_rf = get_clean_model(model_bundle["rf_model"])
        return shap.TreeExplainer(clean_rf)

@st.cache_data(show_spinner=False)
def _get_cached_shap_values(run_id, model_type, sample_indices, _model_bundle, _X_scaled_sample):
    """
    Internal cached function to calculate SHAP values.
    Uses run_id, model_type, and indices as hashing keys while ignoring large objects.
    """
    explainer = get_explainer(_model_bundle)
    
    # Compute SHAP values
    shap_vals = explainer.shap_values(_X_scaled_sample)
    
    if shap_vals is None:
        raise ValueError("SHAP values could not be generated by the explainer.")
        
    # Extract class 1 (Pass) slice
    # Scikit-learn outputs lists [class_0_contrib, class_1_contrib] for binary classifiers
    if isinstance(shap_vals, list):
        if len(shap_vals) > 1:
            shap_vals_plot = shap_vals[1]
            expected_value = explainer.expected_value[1]
        else:
            shap_vals_plot = shap_vals[0]
            expected_value = explainer.expected_value
    elif len(np.array(shap_vals).shape) == 3:
        shap_vals_plot = shap_vals[:, :, 1]
        expected_value = explainer.expected_value[1]
    else:
        shap_vals_plot = shap_vals
        if hasattr(explainer.expected_value, "__len__") and len(explainer.expected_value) > 1:
            expected_value = explainer.expected_value[1]
        else:
            expected_value = explainer.expected_value
            
    return shap_vals_plot, expected_value

def compute_shap_values(model_bundle, X_scaled_sample):
    """
    Computes SHAP values and extracts the correct class-1 slice and base value.
    Delegates to Streamlit cached helper to prevent latency on reruns.
    """
    run_id = model_bundle.get("run_id", "default_run")
    model_type = model_bundle.get("model_type", "default_model")
    sample_indices = list(X_scaled_sample.index)
    
    shap_vals_plot, expected_value = _get_cached_shap_values(
        run_id, model_type, sample_indices, model_bundle, X_scaled_sample
    )
    
    explainer = get_explainer(model_bundle)
    return shap_vals_plot, expected_value, explainer

def plot_beeswarm(model_bundle, X_scaled_sample):
    """
    Generates a global beeswarm summary plot.
    Returns the Matplotlib figure.
    """
    features = model_bundle["features"]
    shap_vals_plot, _, _ = compute_shap_values(model_bundle, X_scaled_sample)
    
    with plot_lock:
        fig = plt.figure(figsize=(9, max(4, len(features) * 0.55)))
        try:
            # Rename features in the plot for readability
            feature_names_readable = [f.replace("_", " ").title() for f in features]
            
            # Explicitly force matplotlib active figure mapping
            shap.summary_plot(
                shap_vals_plot,
                X_scaled_sample,
                feature_names=feature_names_readable,
                show=False,
                plot_size=None
            )
            plt.tight_layout()
        except Exception as e:
            plt.close(fig)
            raise e
            
        return fig

def plot_waterfall(model_bundle, X_scaled_student_row, student_idx=0):
    """
    Generates an individual waterfall explanation plot.
    Returns the Matplotlib figure.
    """
    features = model_bundle["features"]
    explainer = get_explainer(model_bundle)
    
    with plot_lock:
        shap_single = explainer.shap_values(X_scaled_student_row)
        
        if isinstance(shap_single, list):
            if len(shap_single) > 1:
                sv_ind = shap_single[1][0]
                ev_ind = explainer.expected_value[1]
            else:
                sv_ind = shap_single[0][0]
                ev_ind = explainer.expected_value
        elif len(np.array(shap_single).shape) == 3:
            sv_ind = shap_single[0, :, 1]
            ev_ind = explainer.expected_value[1]
        else:
            sv_ind = shap_single[0]
            if hasattr(explainer.expected_value, "__len__") and len(explainer.expected_value) > 1:
                ev_ind = explainer.expected_value[1]
            else:
                ev_ind = explainer.expected_value
                
        # Format explanation object for waterfall plots
        feature_names_readable = [f.replace("_", " ").title() for f in features]
        sv_exp_ind = shap.Explanation(
            values=sv_ind,
            base_values=ev_ind,
            data=X_scaled_student_row.values[0],
            feature_names=feature_names_readable,
        )
        
        fig = plt.figure(figsize=(8, max(3.5, len(features) * 0.45)))
        try:
            shap.plots.waterfall(sv_exp_ind, max_display=len(features), show=False)
            plt.tight_layout()
        except Exception as e:
            plt.close(fig)
            raise e
            
        return fig

def plot_decision(model_bundle, X_scaled_student_row):
    """
    Generates a single student decision flow plot.
    Returns the Matplotlib figure.
    """
    features = model_bundle["features"]
    explainer = get_explainer(model_bundle)
    
    with plot_lock:
        shap_single = explainer.shap_values(X_scaled_student_row)
        
        if isinstance(shap_single, list):
            if len(shap_single) > 1:
                sv = shap_single[1]
                ev = explainer.expected_value[1]
            else:
                sv = shap_single[0]
                ev = explainer.expected_value
        elif len(np.array(shap_single).shape) == 3:
            sv = shap_single[:, :, 1]
            ev = explainer.expected_value[1]
        else:
            sv = shap_single
            if hasattr(explainer.expected_value, "__len__") and len(explainer.expected_value) > 1:
                ev = explainer.expected_value[1]
            else:
                ev = explainer.expected_value
                
        fig = plt.figure(figsize=(6, 4))
        try:
            feature_names_readable = [f.replace("_", " ").title() for f in features]
            shap.decision_plot(
                ev, sv, X_scaled_student_row,
                feature_names=feature_names_readable,
                show=False
            )
            plt.tight_layout()
        except Exception as e:
            plt.close(fig)
            raise e
            
        return fig

def get_mean_shap_importance(model_bundle, X_scaled_sample):
    """
    Extracts global feature importance based on mean absolute SHAP values.
    """
    features = model_bundle["features"]
    try:
        shap_vals_plot, _, _ = compute_shap_values(model_bundle, X_scaled_sample)
        mean_shap = np.abs(shap_vals_plot).mean(axis=0)
        
        importance_dict = {}
        for f, val in zip(features, mean_shap):
            importance_dict[f] = float(val)
        return importance_dict
    except Exception:
        # Fallback to empty importance if calculation fails
        return {f: 0.0 for f in features}

